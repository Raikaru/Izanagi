#!/usr/bin/env python3
"""Generate SPU pitch coefficients mathematically; optionally verify retail LIBSD.

Each coefficient is floor(32768 * 2**(n/d)). Integer nth roots avoid relying
on a host libm even at generation time. LIBSD.IRX uses d=12 and d=1536;
its unchanged Note2Pitch instructions load these tables at 0x54c0/0x54d8.
"""
import argparse
from pathlib import Path
import struct


def coefficient(n, denominator):
    target = 1 << (15 * denominator + n)
    low, high = 0x8000, 0x10000
    while low + 1 < high:
        middle = (low + high) // 2
        if middle ** denominator <= target:
            low = middle
        else:
            high = middle
    return low


def retail_table(path):
    data = path.read_bytes()
    offset = struct.unpack_from('<I', data, 32)[0]
    stride, count = struct.unpack_from('<HH', data, 46)
    for i in range(count):
        _, kind, _, address, file_offset, size, *_ = struct.unpack_from('<10I', data, offset + i * stride)
        if kind == 1 and address <= 0x54c0 and 0x54c0 + 280 <= address + size:
            return struct.unpack_from('<140H', data, file_offset + 0x54c0 - address)
    raise ValueError('LIBSD.IRX has no Note2Pitch coefficient window')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True, type=Path)
    parser.add_argument('--verify-irx', type=Path)
    parser.add_argument('--check', action='store_true', help='compare the checked-in table without modifying it')
    args = parser.parse_args()
    notes = [coefficient(n, 12) for n in range(12)]
    fine = [coefficient(n, 1536) for n in range(128)]
    if args.verify_irx:
        actual = retail_table(args.verify_irx)
        if tuple(notes + fine) != actual:
            raise ValueError('mathematical coefficients differ from retail LIBSD.IRX')
        print('SPU pitch: all 140 mathematical coefficients equal retail LIBSD.IRX')
    text = ['/* Generated by tools/spu_pitch_table.py using exact integer roots.',
            ' * Mathematical coefficients, not extracted retail data. */',
            '#ifndef P4PC_SPU_PITCH_TABLE_H', '#define P4PC_SPU_PITCH_TABLE_H', '', '#include <stdint.h>', '']
    for name, values in [('semitone', notes), ('fine', fine)]:
        text.append(f'static const uint16_t p4spu_{name}[{len(values)}] = {{')
        for i in range(0, len(values), 8):
            text.append('    ' + ', '.join(f'0x{value:04x}' for value in values[i:i+8]) + ',')
        text.extend(['};', ''])
    text.append('#endif')
    generated = '\n'.join(text) + '\n'
    if args.check:
        if args.out.read_text(encoding='utf-8') != generated:
            raise ValueError('checked-in SPU coefficients differ from their exact mathematical definition')
        print('SPU pitch: checked-in coefficients match exact integer roots')
    else:
        args.out.write_text(generated, encoding='utf-8')


if __name__ == '__main__':
    main()
