#!/usr/bin/env python3
"""Place the names the generator cannot place, from the retail binary.

The decomp's PS2 MIPS objects hold every relocation against an unplaced name.
Only a function whose object bytes equal retail exactly (relocated immediates
masked) says anything about retail addresses, so only those sites are used.
For each such site the retail instruction decodes to the symbol's address:
  GPREL16          S = gp + simm16(retail) - simm16(object)
  CALL26           S = target(retail) - addend(object)
  HI16 + LO16      S = hilo(retail) - hilo(object)   (same symbol, paired)
A site whose retail matches disagree (a function with two retail copies) is
skipped as ambiguous. A name is placed only if at least one site is accepted
and every accepted site agrees. Disagreement, an undecodable site, or a name
with no accepted site is fatal; nothing is written.

Output: `name 0xADDR data|func  # evidence` lines read by tools/gen_port.py.
"""

import argparse
import os
import struct
import sys
from collections import defaultdict
from pathlib import Path
from typing import NamedTuple

GP = 0x007690F0
TEXT_BASE = 0x00100000

PT_LOAD = 1
SHT_SYMTAB = 2
SHT_REL = 9
STT_FUNC = 2

R_MIPS_32 = 2
R_MIPS_26 = 4
R_MIPS_HI16 = 5
R_MIPS_LO16 = 6
R_MIPS_GPREL16 = 7
R_MIPS_GOT16 = 9
R_MIPS_GPREL32 = 12
REL_NAMES = {
    R_MIPS_32: "abs32",
    R_MIPS_26: "call26",
    R_MIPS_HI16: "hi16",
    R_MIPS_LO16: "lo16",
    R_MIPS_GPREL16: "gprel16",
    R_MIPS_GOT16: "got16",
    R_MIPS_GPREL32: "gprel32",
}

HEADER = """# Placements for undefined names that the decomp's symbol lists do not give.
# Read by tools/gen_port.py (tables). One name per line: `name 0xADDR data|func`.
# Generated by tools/retail_symbols.py from the retail binary (see its docstring);
# do not hand-edit. Re-run the tool after the unplaced list changes.
"""


class Rel(NamedTuple):
    off: int
    typ: int
    name: str


class Func(NamedTuple):
    name: str
    value: int
    size: int


def sext16(x):
    x &= 0xFFFF
    return x - 0x10000 if x & 0x8000 else x


def u32(data, off):
    return struct.unpack_from("<I", data, off)[0]


def cstr(data, off):
    return data[off:data.index(b"\0", off)].decode("latin-1")


class Retail:
    """The retail ELF: one file-backed PT_LOAD at TEXT_BASE, read by virtual address."""

    def __init__(self, path):
        self.data = Path(path).read_bytes()
        d = self.data
        if d[:4] != b"\x7fELF" or d[4] != 1 or d[5] != 1:
            sys.exit(f"{path}: not a little-endian ELF32")
        phoff, = struct.unpack_from("<I", d, 0x1C)
        phentsize, phnum = struct.unpack_from("<HH", d, 0x2A)
        loads = []
        for i in range(phnum):
            p_type, p_offset, p_vaddr, _p, p_filesz, _m = struct.unpack_from(
                "<6I", d, phoff + i * phentsize)
            if p_type == PT_LOAD and p_filesz:
                loads.append((p_vaddr, p_offset, p_filesz))
        if len(loads) != 1 or loads[0][0] != TEXT_BASE:
            sys.exit(f"{path}: expected one file-backed PT_LOAD at 0x{TEXT_BASE:x}, got {loads}")
        self.va, self.off, self.size = loads[0]
        self.end = self.va + self.size

    def word(self, va):
        if va % 4 or not (self.va <= va and va + 4 <= self.end):
            return None
        return u32(self.data, self.off + va - self.va)


class Obj:
    """One ELF32 little-endian MIPS relocatable: sections, functions, REL relocations."""

    def __init__(self, path, data):
        self.path = path
        self.data = data
        shoff, = struct.unpack_from("<I", data, 0x20)
        shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x2E)
        raw = [struct.unpack_from("<10I", data, shoff + i * shentsize) for i in range(shnum)]
        names_off = raw[shstrndx][4]
        self.secs = []
        for nm, typ, _flags, _addr, off, size, link, info, _al, _es in raw:
            self.secs.append((cstr(data, names_off + nm), typ, off, size, link, info))
        syms = []
        symtab = next((s for s in self.secs if s[1] == SHT_SYMTAB), None)
        if symtab is not None:
            strtab = self.secs[symtab[4]]
            for k in range(symtab[3] // 16):
                st_name, st_value, st_size, st_info, _o, st_shndx = struct.unpack_from(
                    "<IIIBBH", data, symtab[2] + 16 * k)
                syms.append((cstr(data, strtab[2] + st_name), st_value, st_size,
                             st_info & 0xF, st_shndx))
        self.rels = defaultdict(list)  # target section index -> relocs sorted by offset
        for _name, typ, off, size, _link, info in self.secs:
            if typ != SHT_REL:
                continue
            for k in range(size // 8):
                r_off, r_info = struct.unpack_from("<II", data, off + 8 * k)
                self.rels[info].append(Rel(r_off, r_info & 0xFF, syms[r_info >> 8][0]))
        for lst in self.rels.values():
            lst.sort(key=lambda r: r.off)
        self.funcs = defaultdict(list)  # section index -> functions
        for name, value, size, typ, shndx in syms:
            if typ == STT_FUNC and size and shndx:
                self.funcs[shndx].append(Func(name, value, size))

    def sec_bytes(self, idx):
        _name, _typ, off, size, _link, _info = self.secs[idx]
        return self.data[off:off + size]


def function_sites(obj, tgt, f, frels):
    """(name, type, offsets) per relocation site in f; HI16 is paired with its LO16."""
    sites = []
    pending = []  # HI16 relocs still waiting for their LO16, in offset order
    for r in frels:
        where = f"{obj.path.name}:{f.name}+0x{r.off - f.value:x}"
        if r.typ == R_MIPS_HI16:
            pending.append(r)
        elif r.typ == R_MIPS_LO16:
            hi = next((h for h in reversed(pending) if h.name == r.name), None)
            if hi is None:
                raise ValueError(f"{where}: LO16 of {r.name} has no HI16")
            pending.remove(hi)
            sites.append((r.name, R_MIPS_HI16, (hi.off, r.off)))
        elif r.typ in (R_MIPS_GPREL16, R_MIPS_26):
            sites.append((r.name, r.typ, (r.off,)))
        else:
            kind = REL_NAMES.get(r.typ, str(r.typ))
            raise ValueError(f"{where}: {kind} of {r.name} inside code is not decoded")
    if pending:
        raise ValueError(f"{obj.path.name}:{f.name}: HI16 of {pending[0].name} has no LO16")
    return sites


def locate(retail, obj, tgt, f, frels):
    """Retail VAs where f's object bytes match, with relocated immediates masked."""
    body = obj.sec_bytes(tgt)
    if f.size % 4:
        raise ValueError(f"{f.name}: size {f.size} is not whole words")
    n = f.size // 4
    words = struct.unpack_from("<%dI" % n, body, f.value)
    masks = [0xFFFFFFFF] * n
    for r in frels:
        i = (r.off - f.value) // 4
        if r.typ in (R_MIPS_HI16, R_MIPS_LO16, R_MIPS_GPREL16):
            masks[i] &= 0xFFFF0000
        elif r.typ == R_MIPS_26:
            masks[i] &= 0xFC000000
        else:
            raise ValueError(f"{f.name}: relocation {REL_NAMES.get(r.typ, r.typ)} in code")
    # Anchor on the rarest fully-known word: the first one that is not a nop or jr ra.
    anchor = next((i for i, m in enumerate(masks)
                   if m == 0xFFFFFFFF and words[i] not in (0, 0x03E00008)), None)
    if anchor is None:
        anchor = next((i for i, m in enumerate(masks) if m == 0xFFFFFFFF), None)
    if anchor is None:
        raise ValueError(f"{f.name}: no fully-known word to anchor the search")
    pat = struct.pack("<I", words[anchor])
    buf = retail.data
    end = retail.off + retail.size
    hits = []
    pos = buf.find(pat, retail.off, end)
    while pos != -1:
        va = retail.va + (pos - retail.off) - 4 * anchor
        if va % 4 == 0 and va >= retail.va and va + 4 * n <= retail.end:
            ok = True
            for i in range(n):
                rw = retail.word(va + 4 * i)
                if rw is None or (rw & masks[i]) != (words[i] & masks[i]):
                    ok = False
                    break
            if ok:
                hits.append(va)
        pos = buf.find(pat, pos + 1, end)
    return sorted(set(hits))


def decode_site(retail, obj, tgt, f, fn_va, site):
    """Address S that one site refers to, read from the retail instruction(s)."""
    name, typ, offs = site
    sec = obj.sec_bytes(tgt)

    def rva(off):
        return fn_va + (off - f.value)

    def rword(off):
        w = retail.word(rva(off))
        if w is None:
            raise ValueError(f"retail word 0x{rva(off):08x} is outside the image")
        return w

    if typ == R_MIPS_GPREL16:
        off, = offs
        return (GP + sext16(rword(off)) - sext16(u32(sec, off))) & 0xFFFFFFFF
    if typ == R_MIPS_26:
        off, = offs
        target = ((rva(off) + 4) & 0xF0000000) | ((rword(off) & 0x03FFFFFF) << 2)
        return (target - ((u32(sec, off) & 0x03FFFFFF) << 2)) & 0xFFFFFFFF
    hoff, loff = offs
    e = (((rword(hoff) & 0xFFFF) << 16) + sext16(rword(loff))) & 0xFFFFFFFF
    a = (((u32(sec, hoff) & 0xFFFF) << 16) + sext16(u32(sec, loff))) & 0xFFFFFFFF
    return (e - a) & 0xFFFFFFFF


def read_names(path):
    return [line.split("\t")[0].strip() for line in Path(path).read_text().splitlines()
            if line.strip()]


def load_objects(objdir, names):
    needles = [n.encode() for n in names]
    objs = []
    for root, dirs, files in os.walk(objdir):
        dirs[:] = [d for d in dirs if d != "cache"]
        for fn in sorted(files):
            if not fn.endswith(".o"):
                continue
            p = Path(root) / fn
            data = p.read_bytes()
            if any(nd in data for nd in needles):
                objs.append(Obj(p, data))
    return objs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument("--retail", required=True, type=Path)
    ap.add_argument("--objdir", required=True, type=Path)
    ap.add_argument("--unplaced", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--evidence", type=Path)
    ap.add_argument("--partial", action="store_true",
                    help="write the names that place; report the rest as unplaced")
    a = ap.parse_args(argv)

    names = read_names(a.unplaced)
    wanted = set(names)
    retail = Retail(a.retail)
    objs = load_objects(a.objdir, names)

    errors = []
    accepted = defaultdict(list)  # name -> [(S, where, typ)]
    skipped = defaultdict(list)   # name -> [reason]
    nfuncs = nmatched = 0

    for obj in objs:
        for tgt in sorted(obj.funcs):
            for f in obj.funcs[tgt]:
                frels = [r for r in obj.rels.get(tgt, []) if f.value <= r.off < f.value + f.size]
                if not any(r.name in wanted for r in frels):
                    continue
                nfuncs += 1
                where = f"{obj.path.name}:{f.name}"
                try:
                    sites = [s for s in function_sites(obj, tgt, f, frels) if s[0] in wanted]
                    cands = locate(retail, obj, tgt, f, frels)
                except ValueError as e:
                    errors.append(str(e))
                    continue
                if not cands:
                    for s in sites:
                        skipped[s[0]].append(f"{where} not byte-matched in retail")
                    continue
                nmatched += 1
                if f.name.startswith("func_"):
                    try:
                        want = int(f.name[5:], 16)
                    except ValueError:
                        want = None
                    if want is not None and want not in cands:
                        errors.append(f"{where}: name says 0x{want:08x}, "
                                      f"retail matches {[hex(c) for c in cands]}")
                        continue
                for site in sites:
                    name, typ, offs = site
                    at = f"{where}+0x{offs[0] - f.value:x}"
                    try:
                        vals = {decode_site(retail, obj, tgt, f, fn_va, site) for fn_va in cands}
                    except ValueError as e:
                        errors.append(f"{name}: {at}: {e}")
                        continue
                    if len(vals) != 1:
                        skipped[name].append(f"{at} ambiguous ({len(cands)} retail matches)")
                        continue
                    accepted[name].append((vals.pop(), at, typ))

    placed = {}
    unplaced = []
    for name in names:
        acc = accepted.get(name, [])
        if not acc:
            why = "; ".join(skipped.get(name, [])[:3]) or "no PS2 relocation site"
            unplaced.append(f"{name}: no retail site decodes ({why})")
            continue
        vals = {s for s, _, _ in acc}
        if len(vals) != 1:
            detail = "; ".join(f"{at} {REL_NAMES.get(t, t)} -> 0x{s:08x}" for s, at, t in acc)
            errors.append(f"{name}: sites disagree: {detail}")
            continue
        S = vals.pop()
        if not (TEXT_BASE <= S < retail.end):
            errors.append(f"{name}: decoded 0x{S:08x} is outside the retail image")
            continue
        kind = "func" if any(t == R_MIPS_26 for _, _, t in acc) else "data"
        placed[name] = (S, kind, acc)
    if unplaced and not a.partial:
        errors.extend(unplaced)
    if errors:
        for e in errors:
            print("retail_symbols: error: " + e, file=sys.stderr)
        print(f"retail_symbols: {len(errors)} error(s); nothing written", file=sys.stderr)
        return 1
    for e in unplaced:
        print("retail_symbols: unplaced: " + e, file=sys.stderr)

    by_addr = defaultdict(list)
    for name, (S, _kind, _acc) in placed.items():
        by_addr[S].append(name)
    for S, group in sorted(by_addr.items()):
        if len(group) > 1:
            print(f"retail_symbols: note: 0x{S:08x} is shared by {', '.join(sorted(group))}",
                  file=sys.stderr)

    lines = [HEADER]
    for name in sorted(placed):
        S, kind, acc = placed[name]
        head = ", ".join(f"{at} {REL_NAMES.get(t, t)}" for _, at, t in acc[:3])
        more = f" +{len(acc) - 3} more" if len(acc) > 3 else ""
        lines.append(f"{name} 0x{S:08X} {kind}  # {len(acc)} sites agree: {head}{more}\n")
    a.out.write_text("".join(lines))
    if a.evidence:
        with a.evidence.open("w") as fh:
            for name in sorted(placed):
                S, kind, acc = placed[name]
                fh.write(f"{name}\t0x{S:08X}\t{kind}\n")
                for s, at, t in acc:
                    fh.write(f"\t{at}\t{REL_NAMES.get(t, t)}\t0x{s:08X}\n")
    skip_total = sum(len(v) for v in skipped.values())
    print(f"retail_symbols: {nfuncs} functions touch unplaced names, {nmatched} byte-matched, "
          f"{skip_total} site(s) skipped (unmatched or ambiguous)")
    print(f"retail_symbols: placed {len(placed)} of {len(names)} names -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
