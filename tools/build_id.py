#!/usr/bin/env python3
"""Print the C source of the build id: which source tree a binary was built from.

The id comes from the source tree and nothing else (never the time, the host or the build directory), so building one commit twice
gives byte-identical output. It names the git commit and whether the tree had uncommitted changes; a dirty tree cannot be reproduced
from the commit, so the id says so. Resolution order:

  1. P4PC_BUILD_ID   an explicit id from a packaging script: <40 hex>[-dirty]
  2. git             in --source: HEAD, and `-dirty` when a tracked file differs from it or a source file is untracked
  3. P4PC_CHECK_SHA  what a CI container is told (its source tree has no .git): the commit, clean
  4. unknown

Usage: build_id.py --source <tree> [--out <file>]. With --out the file is rewritten only when its content changes (so only that
translation unit rebuilds when the commit does). Also `--print-id` for the id alone.
"""
import argparse
import os
import re
import subprocess
import sys

HEX40 = re.compile(r"^[0-9a-f]{40}$")
# Untracked files only count as a change under these (a build directory inside the tree must not make every build dirty).
SOURCE_DIRS = ("src", "include", "cmake", "zigbuild", "tools", "tests", "config", "third_party", "mods", "overrides", "android")


def run_git(source, *args):
    """(returncode, stdout); returncode None when git cannot be run."""
    try:
        done = subprocess.run(["git", "-C", source, *args], capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return None, ""
    return done.returncode, done.stdout


def git(source, *args):
    code, out = run_git(source, *args)
    return out if code == 0 else None


def resolve(source):
    """(commit or None, dirty)."""
    explicit = os.environ.get("P4PC_BUILD_ID", "").strip()
    match = re.fullmatch(r"([0-9a-f]{40})(-dirty)?", explicit)
    if match:
        return match.group(1), bool(match.group(2))
    head = git(source, "rev-parse", "--verify", "HEAD")
    if head and HEX40.match(head.strip()):
        commit = head.strip()
        # `git diff --quiet` compares content where only the stat data differs (a fresh checkout), unlike diff-index; 1 means a difference.
        changed = run_git(source, "diff", "--quiet", "HEAD", "--")[0] == 1
        if not changed:
            untracked = git(source, "ls-files", "--others", "--exclude-standard", "--", *SOURCE_DIRS)
            changed = bool(untracked and untracked.strip())
        return commit, changed
    ci = os.environ.get("P4PC_CHECK_SHA", "").strip()
    if HEX40.match(ci):
        return ci, False
    return None, False


def render(commit, dirty):
    if commit is None:
        text, full, flag = "unknown", "unknown", 0
    else:
        text, full, flag = commit[:12] + ("-dirty" if dirty else ""), commit, int(dirty)
    return (
        "/* Generated by tools/build_id.py from the source tree: no time, host or path. */\n"
        '#include "p4pc/build_id.h"\n'
        f'const char *p4_build_id(void) {{ return "{text}"; }}\n'
        f'const char *p4_build_commit(void) {{ return "{full}"; }}\n'
        f"int p4_build_dirty(void) {{ return {flag}; }}\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", default=".")
    parser.add_argument("--out")
    parser.add_argument("--print-id", action="store_true")
    args = parser.parse_args()
    commit, dirty = resolve(args.source)
    text = render(commit, dirty)
    if args.print_id:
        print("unknown" if commit is None else commit[:12] + ("-dirty" if dirty else ""))
        return 0
    if not args.out:
        sys.stdout.write(text)
        return 0
    try:
        with open(args.out, encoding="utf-8", newline="") as old:
            if old.read() == text:
                return 0
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="") as out:
        out.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
