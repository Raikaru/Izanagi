pub fn find(codepoint: u32) ?[]const u8 {
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (table[mid].codepoint < codepoint) lo = mid + 1 else hi = mid;
    }
    if (lo < table.len and table[lo].codepoint == codepoint) return table[lo].text;
    return null;
}
