#!/usr/bin/env python3
"""Measure BF instruction/command use and CRI media headers; never write payloads.

The input inventory is generated by inventory.py from the same install. Results
are metadata only, and the inventory's hash is checked against each read object.
BF framing follows docs/golden_mode/specs/battle_tables.md. HCA header layout:
https://reverseengineering.wiki/index.php/Format:HCA
USM has no general container encryption flag; inconclusive streams remain unknown:
https://reverseengineering.wiki/index.php/Format:CRI_USM
"""
import argparse
import bisect
import collections
import hashlib
import json
import re
import struct
import sys
from pathlib import Path

import formats
import inventory
import layouts


def elf_groups(path):
    """Read PS2 VM descriptors and function-presence bits, not executable output."""
    blob = Path(path).read_bytes()
    if blob[:4] != b'\x7fELF' or blob[4:6] != b'\x01\x01':
        raise ValueError('expected a little-endian ELF32')
    phoff = struct.unpack_from('<I', blob, 28)[0]
    width, count = struct.unpack_from('<HH', blob, 42)
    segments = [struct.unpack_from('<8I', blob, phoff + i * width) for i in range(count)]

    def read(address, length):
        for typ, off, va, _, size, _, _, _ in segments:
            if typ == 1 and va <= address and address + length <= va + size:
                return blob[off + address - va:off + address - va + length]
        raise ValueError('PS2 VM address outside file-backed segments')

    groups = []
    for group in range(4):
        ptr, count = struct.unpack('<II', read(0x748530 + group * 8, 8))
        if count > 4096:
            raise ValueError('invalid PS2 command group size')
        entries = read(ptr, count * 8) if count else b''
        groups.append([bool(struct.unpack_from('<I', entries, i * 8)[0]) for i in range(count)])
    return groups


def script(data, groups):
    if len(data) < 112 or data[8:12] != b'FLW0':
        raise ValueError('not a complete BF header')
    sections = {}
    total = struct.unpack_from('<I', data, 16)[0]
    if total != 5:
        raise ValueError('unexpected section count')
    for i in range(total):
        typ, width, count, offset = struct.unpack_from('<4I', data, 32 + i * 16)
        if typ in sections or offset > len(data) or width * count > len(data) - offset:
            raise ValueError('invalid BF section')
        sections[typ] = (width, count, offset)
    if set(sections) != set(range(5)) or sections[0][0] != 32 or sections[2][0] != 4:
        raise ValueError('unexpected BF section types')
    pw, pn, po = sections[0]
    _, count, offset = sections[2]
    procedures = []
    for i in range(pn):
        addr = struct.unpack_from('<I', data, po + i * pw + 24)[0]
        if addr > count:
            raise ValueError('procedure points beyond instruction section')
        procedures.append(addr)
    starts = sorted(set(procedures))
    per_start = {start: collections.Counter() for start in starts}
    commands = collections.Counter()
    bad_ops = collections.Counter()
    pos = 0
    while pos < count:
        opcode, arg = struct.unpack_from('<Hh', data, offset + 4 * pos)
        if opcode == 8:
            commands[arg] += 1
            owner = bisect.bisect_right(starts, pos) - 1
            if owner >= 0:
                per_start[starts[owner]][arg] += 1
        if opcode >= 35 or opcode == 12:
            bad_ops[opcode] += 1
        pos += 2 if opcode in (0, 1) else 1
    if pos != count:
        raise ValueError('truncated immediate')
    missing = {}
    for cmd, uses in commands.items():
        group, index = cmd >> 12, cmd & 0xfff
        if cmd < 0 or group >= len(groups) or index >= len(groups[group]) or not groups[group][index]:
            missing[str(cmd)] = uses
    return {'procedures': len(procedures),
            'procedure_inventory': [{'index': i, 'offset': start,
                                     'commands': dict(sorted(per_start[start].items()))}
                                    for i, start in enumerate(procedures)],
            'instructions': count, 'commands': dict(sorted(commands.items())),
            'missing_commands': missing, 'unsupported_opcodes': dict(sorted(bad_ops.items()))}


def hca(data):
    if len(data) < 8 or bytes(x & 0x7f for x in data[:4]) != b'HCA\0':
        raise ValueError('invalid HCA signature')
    end = struct.unpack_from('>H', data, 6)[0]
    if end < 8 or end > len(data):
        raise ValueError('invalid HCA header size')
    pos = 8
    lengths = {b'fmt\0': 16, b'comp': 16, b'dec\0': 12, b'vbr\0': 8,
               b'ath\0': 6, b'loop': 16, b'ciph': 6, b'rva\0': 8}
    cipher = 0
    while pos + 4 <= end - 2:
        tag = bytes(x & 0x7f for x in data[pos:pos + 4])
        if tag in (b'pad\0', b'comm'):
            break
        width = lengths.get(tag)
        if width is None or pos + width > end - 2:
            raise ValueError('unknown or truncated HCA header chunk')
        if tag == b'ciph':
            cipher = struct.unpack_from('>H', data, pos + 4)[0]
        pos += width
    return {'cipher_type': cipher, 'header_masked': bool(data[0] & 0x80),
            'status': {0: 'clear', 1: 'keyless', 56: 'keyed'}.get(cipher, 'unknown')}


def amd_members(data, parent, depth=0, groups=None):
    """Describe CHNK members, including embedded GMO; never return payloads.

    Framing evidence: https://github.com/Timo654/gmo2amd/blob/master/amd.py
    """
    if depth >= 8 or len(data) < 8 or data[:4] != b'CHNK':
        raise ValueError('invalid AMD chunk header')
    count = struct.unpack_from('<I', data, 4)[0]
    if count > (len(data) - 8) // 24:
        raise ValueError('invalid AMD member count')
    result, pos = [], 8
    for _ in range(count):
        if pos + 24 > len(data):
            raise ValueError('truncated AMD member header')
        name = bytes(data[pos:pos + 16]).split(b'\0', 1)[0].decode('ascii')
        kind, length = struct.unpack_from('<II', data, pos + 16)
        pos += 24
        if not name or length > len(data) - pos:
            raise ValueError('invalid AMD member')
        payload = memoryview(data)[pos:pos + length]
        magic = bytes(payload[:4])
        path = parent + '::' + name
        record = {'path': path, 'kind': 'amd-member', 'type': kind, 'size': length,
                  'sha256': hashlib.sha256(payload).hexdigest(), 'magic': magic.hex(),
                  'signature': 'gmo' if magic == b'OMG.' else formats.signature(bytes(payload[:16]))}
        if record['signature'] == 'flow-bf' and groups is not None:
            record['kind'] = 'bf'
            record.update(script(payload, groups))
        result.append(record)
        if magic == b'CHNK':
            result.extend(amd_members(payload, path, depth + 1, groups))
        pos += length
    if pos < len(data):
        # Preserve unparsed trailing bytes as metadata, not as another CHNK member.
        # Some installed AMDs have eight nonzero bytes after the declared members.
        trailer = memoryview(data)[pos:]
        result.append({'path': parent + '::trailer', 'kind': 'amd-trailer',
                       'size': len(trailer), 'sha256': hashlib.sha256(trailer).hexdigest()})
    return result

def acb_bank_cell(packet):
    """Locate only AwbFile; some ACBs declare unused columns beyond row width."""
    if len(packet) < 32 or packet[:4] != b'@UTF':
        raise ValueError('invalid ACB UTF packet')
    table_size = struct.unpack_from('>I', packet, 4)[0]
    if table_size < 24 or table_size > len(packet) - 8:
        raise ValueError('invalid ACB UTF size')
    table = packet[8:8 + table_size]
    rows, strings, data = struct.unpack_from('>HII', table, 2)
    columns, width, count = struct.unpack_from('>HHI', table, 16)
    if count != 1 or rows > strings or strings > table_size or data > table_size or width > strings - rows:
        raise ValueError('invalid ACB UTF framing')
    cursor, row_cursor = 24, 0
    for _ in range(columns):
        if cursor + 5 > rows:
            raise ValueError('truncated ACB column')
        flags = table[cursor]
        kind, storage = flags & 15, flags & 0xf0
        if kind >= len(formats.UTF_SIZES):
            raise ValueError('invalid ACB column type')
        name_offset = struct.unpack_from('>I', table, cursor + 1)[0]
        name_start = strings + name_offset
        if name_start >= table_size:
            raise ValueError('invalid ACB column name')
        end = table.find(b'\0', name_start)
        if end < 0:
            raise ValueError('unterminated ACB column name')
        name = table[name_start:end]
        cursor += 5
        size = formats.UTF_SIZES[kind]
        if storage == 0x30:
            if cursor + size > rows:
                raise ValueError('truncated ACB constant')
            cell = cursor
            cursor += size
        elif storage == 0x50:
            cell = rows + row_cursor
            row_cursor += size
        elif storage == 0x10:
            cell = None
        else:
            raise ValueError('unsupported ACB column storage')
        if name == b'AwbFile':
            if kind != 11:
                raise ValueError('invalid ACB embedded bank type')
            if cell is None:
                return None
            if cell + 8 > strings:
                raise ValueError('ACB bank cell exceeds row')
            start, length = struct.unpack_from('>II', table, cell)
            if start > table_size - data or length > table_size - data - start:
                raise ValueError('embedded ACB bank exceeds packet')
            return 8 + data + start, length
    return None


def itoc_entries(bank):
    """Read numeric-ID entries from an embedded ITOC-only CPK."""
    read = formats.bytes_reader(bank)
    header = formats.utf_table(formats._chunk(read, 0, b'CPK '))[0]
    offset, content, align = header.get('ItocOffset'), header.get('ContentOffset'), header.get('Align') or 0
    if not offset or not content:
        raise ValueError('embedded CPK lacks ITOC or content')
    packet = formats._chunk(read, offset, b'ITOC')
    if packet[:4] != b'@UTF':
        packet = formats.utf_unmask(packet)
    table = formats.utf_table(packet)
    if len(table) != 1:
        raise ValueError('invalid embedded ITOC')
    entries = []
    for field, count in (('DataL', 'FilesL'), ('DataH', 'FilesH')):
        cell = table[0].get(field)
        expected = table[0].get(count) or 0
        if cell is None:
            if expected:
                raise ValueError('missing embedded ITOC table')
            continue
        start, length = cell
        if start + 8 > len(packet) or length > len(packet) - start - 8:
            raise ValueError('embedded ITOC table out of range')
        rows = formats.utf_table(packet[start + 8:start + 8 + length]) if length else []
        if len(rows) != expected:
            raise ValueError('embedded ITOC count mismatch')
        entries.extend(rows)
    entries.sort(key=lambda row: row['ID'])
    previous = None
    for row in entries:
        ident, size, extracted = row['ID'], row['FileSize'], row['ExtractSize']
        if ident == previous or size is None or extracted is None or content > len(bank) or size > len(bank) - content:
            raise ValueError('invalid embedded ITOC member')
        yield '#%d' % ident, content, size, extracted
        previous = ident
        content += size
        if align:
            content += (-content) % align


def acb_members(data, parent):
    """Measure an ACB's embedded wave bank; https://reverseengineering.wiki/index.php/Format:CRI_ACB."""
    packet = data if data[:4] == b'@UTF' else formats.utf_unmask(data)
    cell = acb_bank_cell(packet)
    if not cell or not cell[1]:
        return []
    offset, length = cell
    bank = packet[offset:offset + length]
    path = parent + '::AwbFile'
    result = [{'path': path, 'kind': 'acb-bank', 'size': len(bank),
               'sha256': hashlib.sha256(bank).hexdigest(), 'magic': bank[:4].hex()}]
    if bank[:4] == b'AFS2':
        entries = inventory.afs2_entries(bank)
        if entries is None and len(bank) >= 16 and struct.unpack_from('<I', bank, 8)[0] == 0:
            entries = []
        if entries is None:
            raise ValueError('malformed embedded AFS2 bank')
        items = ((name, bank[offset:offset + size]) for name, offset, size in entries)
    elif bank[:4] == b'CPK ':
        header = formats.utf_table(formats._chunk(formats.bytes_reader(bank), 0, b'CPK '))[0]
        entries = (formats.cpk_entries(formats.bytes_reader(bank)) if header.get('TocOffset')
                   else itoc_entries(bank))
        def cpk_items():
            for name, offset, stored, extracted in entries:
                raw = bank[offset:offset + stored]
                if len(raw) != stored:
                    raise ValueError('truncated embedded CPK member')
                yield name, formats.crilayla(raw) if raw[:8] == b'CRILAYLA' and stored != extracted else raw
        items = cpk_items()
    else:
        raise ValueError('unknown embedded ACB bank')
    for name, item in items:
        if len(item) >= 4 and bytes(x & 0x7f for x in item[:4]) == b'HCA\0':
            record = {'path': path + '::' + name, 'kind': 'hca', 'size': len(item),
                      'sha256': hashlib.sha256(item).hexdigest()}
            record.update(hca(item))
            result.append(record)
    return result



def scan(install, rows, groups):
    root = Path(install)
    expected = {r['path']: r['sha256'] for r in rows if r.get('depth') == 0 and
                r.get('kind') == 'cri-cpk' and not r.get('error')}
    actual = {p.relative_to(root).as_posix() for p in root.rglob('*') if p.is_file() and p.suffix.lower() == '.cpk'}
    if not expected or set(expected) != actual:
        return [], [{'error': 'inventory does not cover exactly the installed CPKs'}]
    for archive, digest in sorted(expected.items()):
        if inventory.hash_file(root / archive)[0] != digest:
            return [], [{'archive': archive, 'error': 'archive differs from inventory'}]
    targets = {}
    for row in rows:
        if row.get('depth', 0) < 1:
            continue
        sig, path = row.get('signature'), row['path']
        if (sig not in ('flow-bf', 'cri-hca', 'cri-usm', 'amd-chunk') and row.get('magic') != 'c8c3c180'
                and not path.lower().endswith(('/aicalc.tbl', '.acb', '.acx'))):
            continue
        parts = path.split(inventory.SEPARATOR)
        targets.setdefault((parts[0], parts[1].lower()), []).append((parts[2:], row))
    result, errors = [], []
    pending = set(targets)
    for archive in sorted({a for a, _ in targets}):
        with (Path(install) / archive).open('rb') as handle:
            for name, offset, stored, extracted in formats.cpk_entries(formats.file_reader(handle)):
                wanted = targets.get((archive, name.lower()))
                if not wanted:
                    continue
                pending.discard((archive, name.lower()))
                handle.seek(offset)
                data = handle.read(stored)
                try:
                    if len(data) != stored:
                        raise ValueError('short archive read')
                    if data[:8] == b'CRILAYLA' and stored != extracted:
                        data = formats.crilayla(data)
                except (ValueError, formats.FormatError, struct.error) as exc:
                    errors.append({'archive': archive, 'member': name, 'error': str(exc)})
                    continue
                parents = {(): data}
                indexes = {}
                for chain, row in wanted:
                    try:
                        item = data
                        prefix = ()
                        for depth, part in enumerate(chain):
                            if prefix not in indexes:
                                _, entries = inventory.children(item)
                                table = collections.defaultdict(list)
                                for child_name, child_offset, child_size in entries or ():
                                    table[child_name.lower()].append((child_offset, child_size))
                                indexes[prefix] = table
                            matches = indexes[prefix].get(part.lower(), ())
                            if len(matches) > 1 and depth + 1 == len(chain):
                                candidates = []
                                for o, s in matches:
                                    value = item[o:o + s]
                                    if value[:8] == b'CRILAYLA':
                                        value = formats.crilayla(value)
                                    if hashlib.sha256(value).hexdigest() == row['sha256']:
                                        candidates.append((o, s))
                                matches = candidates[:1]
                            if len(matches) != 1:
                                raise ValueError('nested member not uniquely found')
                            next_prefix = prefix + (part.lower(),)
                            if next_prefix in parents:
                                item = parents[next_prefix]
                            else:
                                o, s = matches[0]
                                item = item[o:o + s]
                                if item[:8] == b'CRILAYLA':
                                    item = formats.crilayla(item)
                                if depth + 1 < len(chain):
                                    parents[next_prefix] = item
                            prefix = next_prefix
                        if hashlib.sha256(item).hexdigest() != row['sha256']:
                            raise ValueError('object differs from inventory')
                        record = {'path': row['path'], 'sha256': row['sha256'], 'size': len(item)}
                        if row['path'].lower().endswith('/aicalc.tbl'):
                            spans = layouts.tbl_spans(item)
                            if spans is None:
                                raise ValueError('malformed AICALC table')
                            for index, (_, payload) in enumerate(spans):
                                if payload[8:12] != b'FLW0':
                                    continue
                                child = {'path': row['path'] + '::block:%d' % index,
                                         'sha256': hashlib.sha256(payload).hexdigest(),
                                         'size': len(payload), 'kind': 'bf'}
                                child.update(script(payload, groups))
                                result.append(child)
                            continue
                        if row.get('signature') == 'amd-chunk':
                            result.extend(amd_members(item, row['path'], groups=groups))
                            continue
                        if row['path'].lower().endswith(('.acb', '.acx')):
                            result.extend(acb_members(item, row['path']))
                            continue
                        if row.get('signature') == 'flow-bf':
                            record['kind'] = 'bf'; record.update(script(item, groups))
                        elif row.get('signature') == 'cri-usm':
                            record['kind'] = 'usm'; record['status'] = 'unknown'
                        else:
                            record['kind'] = 'hca'; record.update(hca(item))
                        result.append(record)
                    except (ValueError, formats.FormatError, struct.error) as exc:
                        errors.append({'path': row['path'], 'error': str(exc)})
    errors.extend({'archive': archive, 'member': name, 'error': 'member missing from archive'}
                  for archive, name in sorted(pending))
    return result, errors



def summarize(rows, records, errors):
    formats_by_signature = collections.defaultdict(lambda: {'count': 0, 'bytes': 0, 'stored_bytes': 0})
    extensions = collections.defaultdict(lambda: {'count': 0, 'bytes': 0})
    containers = collections.defaultdict(lambda: {'count': 0, 'bytes': 0})
    for row in rows:
        if row.get('depth', 0) < 1 or not row.get('archive', '').lower().endswith('.cpk'):
            continue
        value = formats_by_signature[row.get('signature', 'unknown')]
        value['count'] += 1
        value['bytes'] += row.get('size', 0)
        value['stored_bytes'] += row.get('stored', 0)
        ext = Path(row['path'].split(inventory.SEPARATOR)[-1]).suffix.lower() or '(none)'
        extensions[ext]['count'] += 1
        extensions[ext]['bytes'] += row.get('size', 0)
        if row.get('kind'):
            containers[row['kind']]['count'] += 1
            containers[row['kind']]['bytes'] += row.get('size', 0)
    modules = {}
    for record in records:
        if record['kind'] != 'bf':
            continue
        path = record['path'].lower().replace('::', '/')
        module = next((label for label, keys in (
            ('battle', ('/battle/', '/btl/')),
            ('social', ('/cmm/', '/comu/', '/comu', '/cmm')),
            ('facility', ('/fcl/', '/facility/')),
            ('field', ('/field/', '/fld/')),
            ('event', ('/event/', '/evt/', '/event_data/')),
            ('common', ('/scheduler/',))) if any(key in path for key in keys)), 'other')
        item = modules.setdefault(module, {'scripts': 0, 'procedures': 0,
                                            'commands': collections.Counter(), 'missing_commands': collections.Counter()})
        item['scripts'] += 1
        item['procedures'] += record['procedures']
        item['commands'].update(record['commands'])
        item['missing_commands'].update(record['missing_commands'])
    media = collections.Counter((r['kind'], r['status']) for r in records if r['kind'] in ('hca', 'usm'))
    embedded = collections.defaultdict(lambda: {'count': 0, 'bytes': 0})
    for record in records:
        if record['kind'] == 'amd-member':
            embedded[record['signature']]['count'] += 1
            embedded[record['signature']]['bytes'] += record['size']
    banks = [r for r in records if r['kind'] == 'acb-bank']
    return {'formats': dict(sorted(formats_by_signature.items())), 'extensions': dict(sorted(extensions.items())),
            'containers': dict(sorted(containers.items())),
            'embedded_acb_banks': {'count': len(banks), 'bytes': sum(r['size'] for r in banks)},
            'embedded_amd_formats': dict(sorted(embedded.items())),
            'script_modules': modules, 'media': {'%s:%s' % pair: count for pair, count in sorted(media.items())},
            'record_count': len(records), 'error_count': len(errors),
            'note': 'Nested object byte totals overlap. Module classification is path-based, not a reachability claim.'}

def write_output(out, rows, records, errors):
    with (out / 'scripts-media.jsonl').open('w', encoding='utf-8', newline='\n') as f:
        for record in records:
            f.write(json.dumps(record, sort_keys=True) + '\n')
    (out / 'scripts-media-errors.json').write_text(json.dumps(errors, indent=2) + '\n', encoding='utf-8')
    (out / 'census-summary.json').write_text(json.dumps(summarize(rows, records, errors), indent=2, sort_keys=True) + '\n', encoding='utf-8')

def verify_steam(install):
    root = Path(install).resolve()
    if root.parent.name.lower() != 'common' or root.parent.parent.name.lower() != 'steamapps':
        raise ValueError('install is not under a Steam library steamapps/common directory')
    manifest = root.parent.parent / 'appmanifest_1113000.acf'
    text = manifest.read_text(encoding='utf-8')
    fields = dict(re.findall(r'"(appid|installdir|buildid)"\s*"([^"]+)"', text, re.IGNORECASE))
    fields = {key.lower(): value for key, value in fields.items()}
    if fields.get('appid') != '1113000' or fields.get('buildid') != '10836033' or fields.get('installdir') != root.name:
        raise ValueError('Steam manifest does not identify the supported install')
    return root



def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--install', required=True)
    ap.add_argument('--inventory', required=True)
    ap.add_argument('--elf', required=True)
    ap.add_argument('--out', required=True)
    args = ap.parse_args()
    verify_steam(args.install)
    out = inventory.check_output(args.out, args.install)
    out.mkdir(parents=True, exist_ok=True)
    with open(args.inventory, encoding='utf-8') as f:
        rows = [json.loads(line) for line in f]
    groups = elf_groups(args.elf)
    records, errors = scan(args.install, rows, groups)
    write_output(out, rows, records, errors)
    print('records %d errors %d' % (len(records), len(errors)))
    return bool(errors)


if __name__ == '__main__':
    sys.exit(main())
