"""tools/build_id.py: the build id names the source tree's commit and dirty flag, and nothing else (no time, host or path)."""
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import unittest

TOOL = pathlib.Path(__file__).resolve().parents[1] / "tools" / "build_id.py"
CLEAN_ENV = {k: v for k, v in os.environ.items() if k not in ("P4PC_BUILD_ID", "P4PC_CHECK_SHA")}


def tool(source, *args, **env):
    environment = dict(CLEAN_ENV)
    environment.update(env)
    done = subprocess.run([sys.executable, str(TOOL), "--source", str(source), *args], capture_output=True, text=True, env=environment)
    assert done.returncode == 0, done.stderr
    return done.stdout


def git(repo, *args):
    subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@t", *args], check=True, capture_output=True)


@unittest.skipUnless(shutil.which("git"), "git is needed")
class BuildIdTest(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.repo = pathlib.Path(self.dir.name) / "tree"
        (self.repo / "src").mkdir(parents=True)
        (self.repo / "src" / "a.c").write_text("int a;\n")
        git(self.repo, "init", "-q")
        git(self.repo, "add", "-A")
        git(self.repo, "commit", "-q", "-m", "one")
        self.commit = subprocess.run(["git", "-C", str(self.repo), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()

    def tearDown(self):
        self.dir.cleanup()

    def test_clean_tree_names_its_commit(self):
        self.assertEqual(tool(self.repo, "--print-id").strip(), self.commit[:12])
        text = tool(self.repo)
        self.assertIn(f'"{self.commit[:12]}"', text)
        self.assertIn(f'"{self.commit}"', text)
        self.assertIn("p4_build_dirty(void) { return 0; }", text)

    def test_output_is_a_function_of_the_tree_alone(self):
        first = tool(self.repo)
        os.utime(self.repo / "src" / "a.c", (1, 1))  # a new mtime is not a change
        self.assertEqual(tool(self.repo), first)
        self.assertEqual(tool(self.repo, TZ="Asia/Tokyo", LANG="ja_JP.UTF-8", SOURCE_DATE_EPOCH="1"), first)
        for word in ("time", "date", "host", str(self.repo)):
            self.assertNotIn(word, first.replace("Generated by tools/build_id.py from the source tree: no time, host or path.", ""))

    def test_tracked_edit_and_untracked_source_make_it_dirty(self):
        (self.repo / "src" / "a.c").write_text("int a = 1;\n")
        self.assertEqual(tool(self.repo, "--print-id").strip(), self.commit[:12] + "-dirty")
        self.assertIn("p4_build_dirty(void) { return 1; }", tool(self.repo))
        git(self.repo, "checkout", "--", "src/a.c")
        self.assertEqual(tool(self.repo, "--print-id").strip(), self.commit[:12])
        (self.repo / "src" / "new.c").write_text("int b;\n")
        self.assertTrue(tool(self.repo, "--print-id").strip().endswith("-dirty"))

    def test_a_build_directory_inside_the_tree_is_not_a_change(self):
        (self.repo / "build").mkdir()
        (self.repo / "build" / "x.o").write_text("object")
        self.assertEqual(tool(self.repo, "--print-id").strip(), self.commit[:12])

    def test_a_new_commit_changes_the_id(self):
        (self.repo / "src" / "a.c").write_text("int a = 2;\n")
        git(self.repo, "commit", "-q", "-am", "two")
        self.assertNotEqual(tool(self.repo, "--print-id").strip(), self.commit[:12])

    def test_explicit_id_and_ci_sha_without_git(self):
        plain = pathlib.Path(self.dir.name) / "plain"
        plain.mkdir()
        sha = "0123456789abcdef0123456789abcdef01234567"
        self.assertEqual(tool(plain, "--print-id").strip(), "unknown")
        self.assertIn('"unknown"', tool(plain))
        self.assertEqual(tool(plain, "--print-id", P4PC_CHECK_SHA=sha).strip(), sha[:12])
        self.assertEqual(tool(plain, "--print-id", P4PC_BUILD_ID=sha + "-dirty").strip(), sha[:12] + "-dirty")
        self.assertEqual(tool(self.repo, "--print-id", P4PC_BUILD_ID=sha).strip(), sha[:12])  # the explicit id wins over git
        self.assertEqual(tool(plain, "--print-id", P4PC_BUILD_ID="not-a-sha").strip(), "unknown")  # a malformed id is ignored
        self.assertEqual(tool(plain, "--print-id", P4PC_CHECK_SHA="xyz").strip(), "unknown")

    def test_out_is_rewritten_only_when_it_changes(self):
        out = pathlib.Path(self.dir.name) / "gen" / "p4_build_id.c"
        tool(self.repo, "--out", str(out))
        self.assertEqual(out.read_text(), tool(self.repo))
        os.utime(out, (1000000000, 1000000000))
        tool(self.repo, "--out", str(out))
        self.assertEqual(out.stat().st_mtime, 1000000000)  # unchanged content: untouched, so nothing recompiles
        (self.repo / "src" / "a.c").write_text("int a = 3;\n")
        tool(self.repo, "--out", str(out))
        self.assertIn("-dirty", out.read_text())


if __name__ == "__main__":
    unittest.main()
