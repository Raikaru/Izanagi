"""Typed mod guards emitted after the ordinary mirror/override passes.

The guard's inactive path is one load/branch. All marshalling and descriptor
lookup stays in its active arm. Host-only invokers live outside the guest-rewritten
mirror, so the two guest ABIs use the same public values without sharing C layouts.
"""
import re

C_TYPES = {"v": "void", "b": "int8_t", "B": "uint8_t", "h": "int16_t", "H": "uint16_t",
           "i": "int32_t", "I": "uint32_t", "q": "int64_t", "Q": "uint64_t", "f": "float", "d": "double", "p": "void *"}


def scalar(text, typedefs, depth=0):
    text = re.sub(r"\b(?:const|volatile|register|extern|static|inline|RWAPI|RWEXPORT)\b", "", text)
    text = " ".join(text.split())
    if "*" in text:
        return "p" if "(" not in text else None
    if text.startswith("enum "):
        return "i"
    # These names have target-dependent host widths. A guest-word typedef
    # may resolve to a native 64-bit parameter after the 64-bit rewrite.
    if text in {"size_t", "__size_t", "ssize_t", "__ssize_t", "ptrdiff_t",
                "intptr_t", "__intptr_t", "uintptr_t", "__uintptr_t",
                "long", "long int", "signed long", "signed long int",
                "unsigned long", "unsigned long int"}:
        return None
    simple = {"void": "v", "char": "b", "signed char": "b", "unsigned char": "B",
              "short": "h", "short int": "h", "signed short": "h", "signed short int": "h", "unsigned short": "H", "unsigned short int": "H",
              "int": "i", "signed": "i", "signed int": "i", "unsigned": "I", "unsigned int": "I",
              "long long": "q", "long long int": "q", "signed long long": "q", "unsigned long long": "Q", "unsigned long long int": "Q",
              "float": "f", "double": "d"}
    if text in simple:
        return simple[text]
    if text in typedefs and depth < 12:
        return scalar(typedefs[text], typedefs, depth + 1)
    return None


def slot(kind):
    return "d" if kind in "fd" else "i" if kind in "bhiq" else "u"


def pack(kind, expression):
    if kind == "p":
        return f"P4_H2G({expression})"
    if kind == "f":
        return f"p4_mod_f32_number({expression})"
    if kind == "d":
        return f"p4_mod_f64_quiet({expression})"
    return f"({'int64_t' if kind in 'bhiq' else 'uint64_t'})({C_TYPES[kind]})({expression})"


def unpack(kind, expression):
    if kind == "p":
        return f"P4_G2H((uint32_t)({expression}))"
    if kind == "f":
        return f"p4_mod_f32_value({expression})"
    return f"({C_TYPES[kind]})({expression})"


def abi_check(kind, expression):
    if kind == "p":
        return f"__builtin_classify_type({expression}) == 5"
    if kind in "fd":
        return f"(__builtin_classify_type({expression}) == 8 && sizeof({expression}) == {4 if kind == 'f' else 8})"
    width = {"b": 1, "B": 1, "h": 2, "H": 2, "i": 4, "I": 4, "q": 8, "Q": 8}[kind]
    check = f"P4_MOD_INTEGER_ABI({expression}, {width})"
    if kind in "bhBH":
        check += f" && {'!' if kind in 'BH' else ''}P4_MOD_SIGNED_ABI({expression})"
    return check


def instrument(mirror, units, build, gp, enabled=True):
    source = ['/* Generated by tools/mod_codegen.py. Never edit. */', '#include "p4pc/mod_hooks.h"', '#include "p4pc/mod_numbers.h"', '#include "p4pc/guest.h"', '#include "p4pc/os.h"']
    report = ["address\tname\tsignature\tunit\tstatus"]
    if not enabled:
        source += ["P4ModFunction *const p4_mod_function_table[] = {0};",
                   "const size_t p4_mod_function_count = 0;"]
        gp.write_if_changed(build / "mod_bridges.c", "\n".join(source) + "\n")
        gp.write_if_changed(build / "mod_hooks.tsv", "\n".join(report) + "\n")
        return 0
    paths = [mirror / unit for unit in units]
    native_names = gp.read_libc_renames()
    texts = {path: path.read_text(encoding="utf-8", errors="surrogateescape") for path in paths}
    headers = [path.read_text(encoding="utf-8", errors="surrogateescape") for path in (mirror / "include").rglob("*.h")]
    typedefs = gp._typedef_classes(list(texts.values()) + headers)
    callbacks = set()
    for text in list(texts.values()) + headers:
        callbacks.update(re.findall(r"typedef\b[^;{}]*\(\s*\*\s*(\w+)\s*\)", text))
    for callback in callbacks:
        typedefs[callback] = "@callback"
    used, registry = set(), []
    total = 0
    for path, text in texts.items():
        edits = []
        unit_typedefs = dict(typedefs)
        unit_typedefs.update(gp._typedef_classes([text]))
        for callback in callbacks:
            unit_typedefs[callback] = "@callback"
        for marker in gp.MARKER_RE.finditer(text):
            address = int(marker[1], 16)
            start = gp.line_end(text, marker.end())
            # Keep marker discovery consistent with the override splicer.
            while text[start:gp.line_end(text, start)].strip().startswith("extern "):
                start = gp.line_end(text, start)
            opening = text.find("{", start)
            if opening < 0:
                continue
            signature = text[start:opening].strip()
            parsed = re.fullmatch(r"(?P<ret>[\w\s*]+?)\b(?P<name>\w+)\s*\((?P<args>[^{};]*)\)", signature)
            if not parsed or "#" in signature or "static" in parsed["ret"].split():
                continue
            name = parsed["name"]
            ret = scalar(parsed["ret"], unit_typedefs)
            raw = gp._split_params(parsed["args"])
            if raw == ["void"] or not raw:
                raw = []
            args, names = [], []
            for arg in raw:
                # Complex declarators/aggregates are explicitly unsupported,
                # never guessed as register-sized integers.
                match = re.fullmatch(r"([\w\s*]+?)([A-Za-z_]\w*)", arg.strip())
                kind = scalar(match[1], unit_typedefs) if match else None
                if not match:
                    match = re.fullmatch(r"([\w\s*]+?)([A-Za-z_]\w*)\s*(?:\[[^\]]*\])+", arg.strip())
                    kind = "p" if match else None
                if not kind or kind == "v":
                    break
                args.append(kind)
                names.append(match[2])
            if not ret or len(args) != len(raw) or len(args) > 12:
                report.append(f"{address:08x}\t{name}\t-\t{path.relative_to(mirror)}\tunsupported signature")
                continue
            if address in used:
                raise ValueError(f"duplicate hookable address {address:08x}")
            used.add(address)
            tag = f"{address:08x}"
            descriptor = f"p4_mod_function_{tag}"
            entry = f"p4_mod_entry_{tag}"
            bridge = f"p4_mod_invoke_{tag}"
            native = f"p4_mod_native_{tag}"
            sig = ret + "".join(args)
            guard = f"p4_mod_guard_{tag}"
            params = ", ".join(C_TYPES[kind] for kind in args) or "void"
            declaration = ", ".join(f"{C_TYPES[kind]} a{i}" for i, kind in enumerate(args)) or "void"
            checks = [f'    _Static_assert({abi_check(kind, arg)}, "mod ABI mismatch {tag} argument {i}");'
                      for i, (kind, arg) in enumerate(zip(args, names))]
            if ret != "v":
                result_expression = f"{name}({', '.join(names)})"
                checks.append(f'    _Static_assert({abi_check(ret, result_expression)}, "mod ABI mismatch {tag} result");')
            lines = ["\n", *checks, f"    extern P4ModEntry {entry};",
                     f"    extern {C_TYPES[ret]} {guard}({params});",
                     f"    if (__builtin_expect({entry}.enabled != 0, 0)) {{" ,
                     f"        if ({entry}.enabled == P4_MOD_BYPASS) {{",
                     f"            {entry}.enabled = {entry}.restore;", "        } else {"]
            guarded_call = f"{guard}({', '.join(names)})"
            lines += ([f"            {guarded_call};", "            return;"] if ret == "v"
                      else [f"            return {guarded_call};"])
            lines += ["        }", "    }\n"]
            edits.append((opening + 1, "\n".join(lines)))
            # Keep marshalling out of the inactive arm even under future LTO;
            # do not inhibit the retail body's normal inlining decisions.
            source += [f"extern P4ModFunction {descriptor};", "__attribute__((noinline))",
                       f"{C_TYPES[ret]} {guard}({declaration}) {{",
                       f"    P4ModValue values[{max(1, len(args))}], result = {{0}};"]
            for i, kind in enumerate(args):
                source.append(f"    values[{i}].{slot(kind)} = {pack(kind, f'a{i}')};")
            source.append(f"    p4_mod_dispatch(&{descriptor}, values, &result);")
            source.append("    return;" if ret == "v" else f"    return {unpack(ret, 'result.' + slot(ret))};")
            source.append("}")
            # Decomp's force-included CRT aliases change the compiled symbol;
            # bridge code is host-compiled and must use that exact retail name.
            native_name = native_names.get(name, name)
            source.append(f'extern {C_TYPES[ret]} {native}({params}) __asm__(P4_ASM_STR(__USER_LABEL_PREFIX__) "{native_name}");')
            source.append(f"static void {bridge}(P4ModValue *a, P4ModValue *r) {{")
            call = f"{native}({', '.join(unpack(kind, f'a[{i}].{slot(kind)}') for i, kind in enumerate(args))})"
            source.append(f"    {call};" if ret == "v" else f"    r->{slot(ret)} = {pack(ret, call)};")
            source += ["}", f"P4ModEntry {entry} = {{0, 0}};",
                       f'P4ModFunction {descriptor} = {{0x{tag}u, &{entry}, "{sig}", {bridge}, 0, 0}};']
            registry.append((address, descriptor))
            report.append(f"{tag}\t{name}\t{sig}\t{path.relative_to(mirror)}\thookable")
            total += 1
        if edits:
            for pos, replacement in sorted(edits, reverse=True):
                text = text[:pos] + replacement + text[pos:]
            gp.write_if_changed(path, '#include "p4pc/mod_entry.h"\n' + text)
    source += ["P4ModFunction *const p4_mod_function_table[] = {",
               *([f"    &{descriptor}," for _, descriptor in sorted(registry)] if registry else ["    0,"]),
               "};", f"const size_t p4_mod_function_count = {total};"]
    gp.write_if_changed(build / "mod_bridges.c", "\n".join(source) + "\n")
    gp.write_if_changed(build / "mod_hooks.tsv", "\n".join(report) + "\n")
    return total
