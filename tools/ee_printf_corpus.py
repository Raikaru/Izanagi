#!/usr/bin/env python3
"""Generate the runtime format corpus from the CRT AST inventory and user ELF.

Retail strings are represented only by addresses. Source-only literals absent
from the ELF remain test inputs; no extracted retail string/data is emitted.
"""
import argparse
import json
from pathlib import Path
import struct

FORMAT_CALLS = {
    "sprintf", "func_00440b68", "func_00446e88", "vsprintf", "func_00446ed8",
    "fclBankLogf", "sdkDbprtQueueText", "H_Dbprt_FmtAt", "H_Dbprt_FmtLog",
    "sdkDbprtQueueColoredText", "sdkDbprtPrint", "func_004cd3f0",
    "sdkDbprtPrintColor", "SVM_CallErr", "MWSFSVM_Error", "LSC_CallErrFunc",
}


def c_string(text):
    result = '"'
    for byte in text.encode("utf-8"):
        if byte in (34, 92):
            result += "\\" + chr(byte)
        elif 32 <= byte < 127:
            result += chr(byte)
        else:
            result += f"\\{byte:03o}"
    return result + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inventory", type=Path)
    parser.add_argument("--elf", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    inventory = json.loads(args.inventory.read_text(encoding="utf-8"))
    image = args.elf.read_bytes()
    phoff = struct.unpack_from("<I", image, 0x1c)[0]
    phsize, phcount = struct.unpack_from("<HH", image, 0x2a)
    segments = []
    for i in range(phcount):
        kind, offset, address, _, size, _, _, _ = struct.unpack_from("<8I", image, phoff+i*phsize)
        if kind == 1:
            segments.append((offset, address, size))
    addresses = set()
    source_literals = set()
    for call in inventory["calls"]:
        if call["name"] not in FORMAT_CALLS:
            continue
        for fmt in call.get("resolved_formats", []):
            if fmt.get("address"):
                addresses.add(int(fmt["address"], 16))
                continue
            text = fmt["text"]
            matches = []
            for encoding in ("utf-8", "shift_jis", "latin1"):
                try:
                    needle = text.encode(encoding)+b"\0"
                except UnicodeEncodeError:
                    continue
                for offset, address, size in segments:
                    found = image.find(needle, offset, offset+size)
                    if found >= 0:
                        matches.append(address+found-offset)
            if matches:
                addresses.add(min(matches))
            else:
                source_literals.add(text)
    rows = [
        "/* Generated by tools/ee_printf_corpus.py. Retail strings stay in the user ELF.",
        " * Non-address literals below are source inputs NOT present in the retail ELF. */",
        "static const struct { uint32_t address; const char *source_literal; } game_formats[] = {",
    ]
    rows += [f"    {{0x{address:08x}u, NULL}}," for address in sorted(addresses)]
    rows += [f"    {{0, {c_string(text)}}}," for text in sorted(source_literals)]
    rows += ["};", ""]
    args.output.write_text("\n".join(rows), encoding="utf-8")
    print(f"format corpus: {len(addresses)} retail addresses + {len(source_literals)} source-only inputs")


if __name__ == "__main__":
    main()
